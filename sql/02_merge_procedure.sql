-- Moves one scoring run from CLV_SCORED_STAGE into CLV_SCORED_OUTPUT.
-- MERGE makes the load safe to rerun: loading the same run twice updates rows instead of
-- duplicating them. (Snowflake does not enforce PRIMARY KEY, so the MERGE is what keeps it unique.)

CREATE OR REPLACE PROCEDURE CLV_DB.ML.SP_MERGE_CLV_SCORES(P_RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    rows_merged INTEGER DEFAULT 0;
BEGIN
    MERGE INTO CLV_DB.ML.CLV_SCORED_OUTPUT t
    USING (SELECT * FROM CLV_DB.ML.CLV_SCORED_STAGE WHERE RUN_ID = :P_RUN_ID) s
       ON t.ARRAY_ID = s.ARRAY_ID
      AND t.SCORE_DATE = s.SCORE_DATE
      AND t.MODEL_VERSION = s.MODEL_VERSION
    WHEN MATCHED THEN UPDATE SET
        t.ACCOUNT_ID           = s.ACCOUNT_ID,
        t.MODEL_NAME           = s.MODEL_NAME,
        t.RUN_ID               = s.RUN_ID,
        t.HAS_LABEL            = s.HAS_LABEL,
        t.UTILIZATION_CAPPED   = s.UTILIZATION_CAPPED,
        t.UTIL_OVER_100_FLAG   = s.UTIL_OVER_100_FLAG,
        t.UTIL_EXCESS          = s.UTIL_EXCESS,
        t.CURRENT_CAPACITY_TB  = s.CURRENT_CAPACITY_TB,
        t.NET_PROFIT_15YR_USD  = s.NET_PROFIT_15YR_USD,
        t.IS_LOSS_MAKING       = s.IS_LOSS_MAKING,
        t.DAYS_TO_CONTRACT_END = s.DAYS_TO_CONTRACT_END,
        t.EXPANSION_SIGNAL     = s.EXPANSION_SIGNAL,
        t.CHURN_PROB_12M       = s.CHURN_PROB_12M,
        t.BASELINE_CHURN_RATE  = s.BASELINE_CHURN_RATE,
        t.RISK_BUCKET          = s.RISK_BUCKET,
        t.SURVIVAL_PROB_15Y    = s.SURVIVAL_PROB_15Y,
        t.HORIZON_BASIS        = s.HORIZON_BASIS,
        t.TOP_DRIVERS          = PARSE_JSON(s.TOP_DRIVERS_JSON),
        t.LOADED_AT            = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (
        ARRAY_ID, ACCOUNT_ID, SCORE_DATE, MODEL_NAME, MODEL_VERSION, RUN_ID, HAS_LABEL,
        UTILIZATION_CAPPED, UTIL_OVER_100_FLAG, UTIL_EXCESS, CURRENT_CAPACITY_TB,
        NET_PROFIT_15YR_USD, IS_LOSS_MAKING, DAYS_TO_CONTRACT_END, EXPANSION_SIGNAL,
        CHURN_PROB_12M, BASELINE_CHURN_RATE, RISK_BUCKET, SURVIVAL_PROB_15Y,
        HORIZON_BASIS, TOP_DRIVERS
    ) VALUES (
        s.ARRAY_ID, s.ACCOUNT_ID, s.SCORE_DATE, s.MODEL_NAME, s.MODEL_VERSION, s.RUN_ID, s.HAS_LABEL,
        s.UTILIZATION_CAPPED, s.UTIL_OVER_100_FLAG, s.UTIL_EXCESS, s.CURRENT_CAPACITY_TB,
        s.NET_PROFIT_15YR_USD, s.IS_LOSS_MAKING, s.DAYS_TO_CONTRACT_END, s.EXPANSION_SIGNAL,
        s.CHURN_PROB_12M, s.BASELINE_CHURN_RATE, s.RISK_BUCKET, s.SURVIVAL_PROB_15Y,
        s.HORIZON_BASIS, PARSE_JSON(s.TOP_DRIVERS_JSON)
    );

    rows_merged := SQLROWCOUNT;

    -- clear this run from the stage so the next load starts clean
    DELETE FROM CLV_DB.ML.CLV_SCORED_STAGE WHERE RUN_ID = :P_RUN_ID;

    RETURN 'Run ' || P_RUN_ID || ': ' || rows_merged || ' rows merged into CLV_SCORED_OUTPUT';
END;
$$;